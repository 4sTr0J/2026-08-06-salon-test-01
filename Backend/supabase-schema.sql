create table if not exists public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  email text not null unique,
  phone text,
  role text not null default 'customer',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.login_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  full_name text,
  email text not null,
  phone text,
  role text,
  user_details jsonb,
  ip_address text,
  user_agent text,
  access_token text,
  logged_in_at timestamptz not null default now(),
  logged_out_at timestamptz,
  is_active boolean not null default true
);

alter table public.users enable row level security;
alter table public.login_logs enable row level security;

create or replace function public.handle_updated_at()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop policy if exists "Profiles are viewable by owner" on public.users;
create policy "Profiles are viewable by owner"
on public.users
for select
using (auth.uid() = id);

drop policy if exists "Profiles can be inserted by owner" on public.users;
create policy "Profiles can be inserted by owner"
on public.users
for insert
with check (auth.uid() = id);

drop policy if exists "Profiles can be updated by owner" on public.users;
create policy "Profiles can be updated by owner"
on public.users
for update
using (auth.uid() = id)
with check (auth.uid() = id);

