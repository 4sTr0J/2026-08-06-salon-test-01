drop policy if exists "Login logs can be inserted by owner" on public.login_logs;
create policy "Login logs can be inserted by owner"
on public.login_logs
for insert
with check (auth.uid() = user_id);

drop policy if exists "Login logs can be updated by owner" on public.login_logs;
create policy "Login logs can be updated by owner"
